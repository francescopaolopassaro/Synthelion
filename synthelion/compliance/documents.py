def _render_open_items(doc: PdfDocument, items: list[str]) -> None:
    if not items:
        return
    doc.heading("Open items requiring human completion", size=12)
    for item in items:
        doc.paragraph(f"-  {item}", indent=6)


def _render_rules_table(doc: PdfDocument, rules: list[dict]) -> None:
    doc.table(
        ["Rule", "Category", "Risk", "Action", "Scope", "On"],
        [[r["id"], r["category"], r["risk_level"], r["action"], r["scope"],
          "yes" if r["enabled"] else "NO"] for r in rules],
        [0.30, 0.16, 0.12, 0.14, 0.14, 0.14],
    )


def _render_matrix(doc: PdfDocument, rows: list[dict]) -> None:
    doc.table(
        ["Module", "Framework", "Article", "Obligation"],
        [[r["module"], r["framework"], r["article"], r["obligation"]] for r in rows],
        [0.22, 0.20, 0.13, 0.45],
    )


def to_pdf(document: dict, path: "str | Path") -> Path:
    """Render any of the four documents to PDF."""
    doc = PdfDocument(
        title=document.get("document", "Compliance Document"),
        subtitle=f"Generated {document.get('generated_at', '')}",
        footer="Synthelion Compliance Engine",
    )

    if document.get("disclaimer"):
        doc.paragraph(document["disclaimer"], size=8.5, gray=0.4)
        doc.rule()

    if "system" in document:
        doc.heading("1. System", size=13)
        doc.key_values([(k.replace("_", " ").title(), str(v)) for k, v in document["system"].items()])

    if "engine" in document:
        engine = document["engine"]
        doc.heading("2. Engine configuration", size=13)
        doc.key_values([
            ("Status", str(engine.get("status"))),
            ("Fallback", str(engine.get("fallback"))),
            ("Agent profile", str(engine.get("agent_profile"))),
            ("Rules enabled", f"{engine.get('rules_enabled')} of {engine.get('rules_total')}"),
        ])

    if document.get("guardrails"):
        doc.heading("3. Active guardrails", size=13)
        _render_rules_table(doc, document["guardrails"])

    if document.get("traceability_matrix"):
        doc.heading("4. Traceability: control to legal obligation", size=13)
        _render_matrix(doc, document["traceability_matrix"])

    if "record_keeping" in document:
        doc.heading("5. Record keeping (Art. 12)", size=13)
        doc.key_values([(k.replace("_", " ").title(), str(v))
                        for k, v in document["record_keeping"].items()])

    if "human_oversight" in document:
        doc.heading("6. Human oversight (Art. 14)", size=13)
        for m in document["human_oversight"]["mechanisms"]:
            doc.paragraph(f"-  {m}", indent=6)

    # DPIA / FRIA specific sections
    for key, title in (("processing_description", "Processing description"),
                       ("measures", "Technical and organisational measures"),
                       ("necessity_and_proportionality", "Necessity and proportionality"),
                       ("deployment_context", "Deployment context")):
        if key in document:
            doc.heading(title, size=13)
            doc.key_values([(k.replace("_", " ").title(), str(v))
                            for k, v in document[key].items()])

    if "risks" in document:
        doc.heading("Risks", size=13)
        for risk in document["risks"].get("identified", []):
            doc.paragraph(f"-  {risk}", indent=6)
        doc.paragraph("Mitigations:", size=9.5)
        for m in document["risks"].get("mitigations", []):
            doc.paragraph(f"-  {m}", indent=6)
        doc.key_values([("Residual risk", str(document["risks"].get("residual_risk_acceptance", "")))])

    if "rights_assessment" in document:
        doc.heading("Fundamental rights assessment", size=13)
        doc.table(
            ["Right", "Impact", "Controls"],
            [[r["right"], r["impact"], ", ".join(r.get("controls", [])) or "—"]
             for r in document["rights_assessment"]],
            [0.26, 0.44, 0.30],
        )

    stats = document.get("statistics")
    if stats:
        doc.heading("Operational statistics", size=13)
        doc.key_values([
            ("Transactions processed", f"{stats['total_calls']:,}"),
            ("With findings", f"{stats['calls_with_findings']:,}"),
            ("Violation rate", f"{stats['violation_rate_pct']}%"),
            ("Latency added (avg / p95 / max)",
             f"{stats['latency_ms']['avg']} / {stats['latency_ms']['p95']} / "
             f"{stats['latency_ms']['max']} ms"),
        ])
        if stats.get("by_category"):
            doc.heading("Findings by category", size=11)
            doc.bar_chart(sorted(stats["by_category"].items(), key=lambda kv: -kv[1]))
        if stats.get("by_risk_level"):
            doc.heading("Findings by risk level", size=11)
            doc.bar_chart(sorted(stats["by_risk_level"].items(), key=lambda kv: -kv[1]))

    if "audit_chain" in document:
        chain = document["audit_chain"]
        doc.heading("Audit trail integrity", size=13)
        doc.key_values([
            ("Entries", str(chain.get("entries"))),
            ("Chain valid", "yes" if chain.get("valid") else "NO — see note"),
            ("Note", chain.get("reason") or "No tampering detected."),
        ])

    ineffective = document.get("ineffective_controls")
    if ineffective:
        doc.heading("Controls enabled but not operational", size=13)
        doc.paragraph("These rules are switched on in the compliance policy, but the guard that "
                      "implements them is disabled or unavailable — they currently inspect "
                      "nothing.", size=9, gray=0.35)
        doc.table(
            ["Rule", "Backend", "State", "Reason"],
            [[h["rule_id"], h["backend"], h["backend_state"], h["note"]] for h in ineffective],
            [0.26, 0.22, 0.16, 0.36],
        )

    gaps = document.get("coverage_gaps")
    if gaps:
        doc.heading("Uncovered obligations (disabled controls)", size=13)
        doc.paragraph("These obligations have no active control in the current configuration.",
                      size=9, gray=0.35)
        _render_matrix(doc, gaps)

    _render_open_items(doc, document.get("open_items", []))
    return doc.save(path)


GENERATORS = {
    "technical-file": technical_file,
    "dpia": dpia,
    "fria": fria,
    "executive-report": executive_report,
}


def generate(kind: str, **kwargs) -> dict:
    if kind not in GENERATORS:
        raise ValueError(f"unknown document {kind!r}; choose from {', '.join(sorted(GENERATORS))}")
    return GENERATORS[kind](**kwargs)
